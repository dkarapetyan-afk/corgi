//! Regenerate the binary's font masks with Bun and Pillow: bun tools/moonlander_glyphs.ts
import { join } from "node:path";
import * as faces from "../src/moonlander/faces";
import { rasterize } from "./moonlander";

const base = faces.layout(40, 88),
  tiles = base.tiles.map((tile, first) => ({ ...tile, first, count: 1 }));
const atlas: faces.Atlas = { ...base, tiles, cols: 3, width: 3 * base.side, height: 3 * base.side };
const alpha = await rasterize(atlas),
  glyphs: Record<string, string> = {};
for (const tile of tiles) {
  const pixels = new Uint8Array(atlas.side ** 2);
  for (let y = 0; y < atlas.side; y++)
    pixels.set(
      alpha.subarray(
        (Math.floor(tile.first / 3) * atlas.side + y) * atlas.width + (tile.first % 3) * atlas.side,
        (Math.floor(tile.first / 3) * atlas.side + y) * atlas.width + ((tile.first % 3) + 1) * atlas.side,
      ),
      y * atlas.side,
    );
  const runs: number[] = [];
  for (let i = 0; i < pixels.length;) {
    let n = 1;
    while (i + n < pixels.length && pixels[i + n] === pixels[i] && n < 255) n++;
    runs.push(n, pixels[i]);
    i += n;
  }
  glyphs[tile.glyph] = Buffer.from(runs).toString("base64");
}
await Bun.write(
  join(import.meta.dir, "../src/moonlander/glyphs.ts"),
  `//! Generated by tools/moonlander_glyphs.ts; count/value alpha runs.\nexport const masks = ${JSON.stringify({ cw: atlas.cw, ch: atlas.ch, side: atlas.side, glyphs }, null, 2)};\n`,
);
